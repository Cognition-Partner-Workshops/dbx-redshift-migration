"""Generate databricks/job/<task>.sql wrappers for the Lakeflow job's SQL file tasks.

Unit SQL uses unqualified silver.x / gold.x names (the validation harness sets
the catalog). SQL file tasks have no catalog setting, so each wrapper prepends
`USE CATALOG IDENTIFIER(:catalog)` to the unit's SQL.

    python tools/sync_job_sql.py           # rewrite wrappers
    python tools/sync_job_sql.py --check   # exit 1 if wrappers are stale
"""
import argparse
import pathlib
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[1]
MANIFEST = ROOT / ".migration" / "units.yaml"
JOB_SQL_DIR = ROOT / "databricks" / "job"
HEADER = (
    "-- GENERATED by tools/sync_job_sql.py from {source}; do not edit.\n"
    "USE CATALOG IDENTIFIER(:catalog);\n\n"
)


def taskName(unitName):
    return "exec_summary" if unitName == "orchestration" else unitName


def expectedWrappers(manifestPath=MANIFEST):
    manifest = yaml.safe_load(manifestPath.read_text())
    wrappers = {}
    for wave in manifest["waves"]:
        for unitName in wave["units"]:
            source = pathlib.Path(manifest["units"][unitName]["target_dir"]) / "etl.sql"
            body = (ROOT / source).read_text()
            wrappers[f"{taskName(unitName)}.sql"] = HEADER.format(source=source.as_posix()) + body
    return wrappers


def staleWrappers():
    expected = expectedWrappers()
    actual = {p.name: p.read_text() for p in JOB_SQL_DIR.glob("*.sql")} if JOB_SQL_DIR.exists() else {}
    stale = sorted(n for n in expected if actual.get(n) != expected[n])
    extra = sorted(set(actual) - set(expected))
    return stale + extra


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        stale = staleWrappers()
        if stale:
            print("stale job SQL wrappers (run python tools/sync_job_sql.py):", ", ".join(stale))
            sys.exit(1)
        return
    JOB_SQL_DIR.mkdir(exist_ok=True)
    expected = expectedWrappers()
    for path in JOB_SQL_DIR.glob("*.sql"):
        if path.name not in expected:
            path.unlink()
    for name, text in expected.items():
        (JOB_SQL_DIR / name).write_text(text)
    print(f"wrote {len(expected)} wrappers to {JOB_SQL_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
